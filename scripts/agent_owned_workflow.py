"""Startup-only instructions for native RAX authorship; no controller/robot execution."""
from pathlib import Path
import hashlib
import json


def install(workspace, *, stage, source=None):
    if stage not in ('exploration', 'function_rehearsal'):
        raise ValueError('Unknown native workflow stage')
    workspace = Path(workspace)
    marker = workspace/'AGENT_OWNERSHIP.md'
    if marker.exists():
        raise FileExistsError('Do not rewrite an existing session workflow')
    refs = workspace/'references'; refs.mkdir(exist_ok=True)
    provenance = {'stage': stage, 'authoring_owner': 'RAX main Agent',
                  'host_role': 'supervise, verify, archive; never silently author or promote task code',
                  'imported_candidate': str(source) if source else None,
                  'candidate_authorship': 'imported; may include Mac-authored code; not newly generated by this session',
                  'imported_code_sha256': {str(p.relative_to(workspace)): hashlib.sha256(p.read_bytes()).hexdigest()
                      for p in sorted((workspace/'code').rglob('*.py')) if p.is_file()},
                  'software_closeout': 'separate phase; no task deadline/call cap'}
    (refs/'agent-workflow-source.json').write_text(json.dumps(provenance, indent=2))
    scope = (
        'Exploration: complete the currently authorized manual task. After its first successful outcome, '
        'stop new task motion, save a short factual checkpoint and end the task turn. '
        'After native shutdown you continue in the separate software phase: distill memory, generate useful '
        'functions from the successful strategy, validate offline and checkpoint the candidate. '
        'Do not start physical function rehearsal, compose main or perform a scene reset merely because exploration succeeded.'
        if stage == 'exploration' else
        'Function rehearsal: you, the RAX main Agent, own experience refinement and function generation/repair. '
        'Read matching successful strategy, turn one useful maneuver into fn(ctx, explicit_inputs), '
        'run relevant offline checks, rehearse that function within the authorized physical scope, '
        'inspect its returned observations/logs, fix it and continue from the measured state. A successful localization or other single function is a checkpoint, not task completion. Implement the next necessary check/function while budget permits; stop only for a concrete physical blocker, user stop, native budget boundary or completed scope. At the task-stage end, save a short checkpoint and end your turn so independent software closeout can begin. '
        'Do not restart manual exploration or compose/run main in this stage.')
    text = '''# Native RAX authoring ownership — new sessions only

## Division of work and stage precedence
The RAX main Agent writes TIPS, distilled strategies/evidence, controller functions,
checks, README and version commits inside this workspace. Mac supervises timing,
operator requests and errors, verifies outputs and archives them. Do not wait for
Mac to write the controller after success. Existing Mac-authored candidates may be
reviewed, reused and repaired; preserve their source hashes and authorship in
references/agent-workflow-source.json. Imported code is not newly Agent-generated
or hardware-qualified simply because it was imported.
This stage note clarifies older task text saying "stop after success/save tips":
that ends task MOTION, not the software closeout described here. It does not expand
hardware authorization, erase unresolved checks, or permit an exploration-to-
rehearsal transition. User stop always stops motion; remaining safe file work may
be saved as partial. Never overwrite source working copies or frozen versions.

## Read once, then work by function
Read TASK.md, memory/INDEX.md, PROGRESS.md, status and only matching tips.
PROGRESS is the engineering checkpoint even before any function has run. The
automatic REHEARSAL_STATE ledger preserves dispatch/results separately; it does not
replace PROGRESS. After each meaningful edit/test record the current function, exact
next command, failed test and files already read. Resume from these, not old startup. Follow .agents/skills/experience-memory/SKILL.md for memory;
read its format reference only when distilling; defer library packaging/merge reads
to software closeout, unless a particular existing skill is needed for this function. Follow
.agents/skills/autonomous-control/SKILL.md for function generation and rehearsal.
Current MCP_SESSION.md/tool schemas outrank examples. On compaction read the newest
state/report and status; do not reread all source or restart completed actions.
A function takes the same ctx down to helpers and explicit current-scene inputs.
Ordinary feedback, geometry and simple perception first; Gemini only for facts
those cannot answer. Do not turn every boundary into a visual model call. No
persistent approval files or wait-for-main-Agent loops inside functions. Return
needs_review for a missing fact; inspect evidence after return. Preserve executed
receipts separately from missing images. Never replay completed movement to recover
an observation. Do not use a constant-true offline checker on real hardware.

## Save while working
After each useful result, update TIPS and PROGRESS with applicable conditions,
tool arguments/pose relations, measured jaw closure and actual feedback (not force),
result, failure/recovery and exact evidence paths. Distill reusable strategies to
memory/skills/<slug>/SKILL.md plus evidence.json and update INDEX. Evidence paths
must point to actual files, not frame directories. Mark human factual assistance,
manual corrections and incomplete functions honestly. Cross-session library merge
is only via the installed continual-learning skill/checker and merge tool if present;
Franka experience-memory by itself does not imply a library merge implementation.

Generate/repair one useful function at a time as evidence permits, rather than
saving all coding for the last turn. For imported code record what you retained or
changed; do not discard useful Mac candidates just to claim original authorship.

## Separate software closeout
Exploration/rehearsal keeps its original task budget and native stop rules. Save
short progress continuously and at the task boundary. Do not reserve task time or
calls for full code generation and closeout. After native Stop/disarm/rest and
child shutdown, the host launches YOUR software-only continuation with the same
workspace and copied native conversation. It has no robot MCP/owner, no auxiliary
vision, no inherited task deadline or call cap. Its model calls and elapsed time
are recorded separately. Mac does not generate your missing functions.
A user interrupt does not automatically restart a model session. If shutdown is
unconfirmed, no automatic continuation starts. Software closeout never reconnects
hardware or grants new motion permission. Finish when the artifacts are complete;
on real blockers/provider errors save partial instead of retrying indefinitely.

## Agent-owned offline checks and version checkpoint
Run relevant syntax/import checks with NO Context/device construction at import,
real tool-schema/input/output checks, and recorded-evidence/negative-case tests for
changed logic. No new framework or exhaustive tests mirroring code are required.
Record commands, exit codes and log paths. These are local engineering checks;
Franka validates behavior through function rehearsal and later varied-layout runs,
not an official "offline suite passed = robot skill complete" rule.

Keep tunables and tested ranges explicit, separate scene localization from reusable
logic, and document single-function entrypoints/preconditions/recovery in the project
README. Commit the controller with ordinary git inside code/<project>/ (initialize
a LOCAL repository if needed); stage only inspected task files, never credentials,
recordings or unrelated state. Preserve history; no amend/reset/push. Copy the commit
ID and code hashes to output/closeout/SUMMARY.json. A candidate/partial commit is
valid but must not be labelled hardware-qualified. Read-only frozen directories plus
hash manifests are host archive protection, not a Franka qualification step.

Write output/closeout/SUMMARY.json with stage, status (partial/candidate_offline_checked/
function_rehearsed), authoring provenance, code project/commit, code hashes, memory
and evidence paths, offline check commands/results/logs, per-function real outcomes,
assistance, timings/model/vision counts, current physical state, unresolved issues
and exact next step. Use actual paths and values; missing tests stay not_run. For
function rehearsal also update output/rehearsal/SUMMARY.json and memory/RUNS.md.
A process exit or saved commit alone is never task success. Host verifies/archives
this report; it must not silently write missing code or fabricate qualification.
Only after all required functions have passed, in a separately authorized composition
stage, may the same functions be combined into main(ctx) and tested on new layouts.
'''
    marker.write_text(scope+'\n\n'+text)
    for name in ('AGENTS.md', 'TASK.md', 'START_PROMPT.md'):
        p=workspace/name
        if not p.is_file():
            continue
        original=p.read_text()
        (refs/('before-agent-ownership-'+name)).write_text(original)
        p.write_text('Current stage/authoring/closeout: read AGENT_OWNERSHIP.md once. '
                     'Its software-closeout requirement supplements the task; hardware scope is unchanged.\n\n'+original)
    return provenance
